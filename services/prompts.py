def get_random_prompts(count: int = 25) -> list[dict]:
    """Возвращает count случайных промптов без повторений."""

    unique_prompts = []
    seen_texts = set()

    for prompt in PROMPTS:
        text = prompt["text"].strip()

        if text not in seen_texts:
            unique_prompts.append(prompt)
            seen_texts.add(text)

    if count < 1:
        raise ValueError("Количество промптов должно быть больше нуля.")

    if count > len(unique_prompts):
        raise ValueError(
            f"Запрошено {count} промптов, "
            f"но уникальных доступно только {len(unique_prompts)}."
        )

    return random.sample(unique_prompts, count)


def get_random_sponatanteous() -> dict:
    """Возвращает случайное задание для спонтанной речи из библиотеки."""
    return random.choice(SPONTANEOUS_TASKS)